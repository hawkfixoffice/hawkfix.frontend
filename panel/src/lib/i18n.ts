export const DICT: Record<Lang, Dict> = { pl, ru, en }

export const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({
  lang: 'pl', setLang: () => {},
})

export function useT() {
  const { lang, setLang } = useContext(LangContext)
  /** Подстановки в строку: t('ord.frozen', { to: '05:00' }). */
  const t = (key: string, vars?: Record<string, string | number>) => {
    const raw = DICT[lang][key] ?? DICT.pl[key] ?? key
    return vars
      ? raw.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m))
      : raw
  }
  return { t, lang, setLang }
}

export function readLang(): Lang {
  try {
    const saved = localStorage.getItem('hawkfix.panel.lang') as Lang | null
    if (saved && LANGS.includes(saved)) return saved
    const nav = navigator.language.slice(0, 2)
    return (LANGS as string[]).includes(nav) ? (nav as Lang) : 'pl'
  } catch { return 'pl' }
}
